    <div class="container">
        <span class="brand-badge">2FA SECURITY CHALLENGE</span>
        <h1>Two-Factor Verification</h1>
        <p class="subtitle">Enter the 6-digit code generated by your <strong>Google Authenticator</strong> app for <code><?= htmlspecialchars($user['email']) ?></code>.</p>

        <div id="alertBox" class="alert alert-error"></div>

        <form id="totpForm">
            <input type="text" id="code" class="otp-input" placeholder="000000" maxlength="18" autocomplete="one-time-code" required autofocus>

            <button type="submit" id="btnSubmit" class="btn-submit">
                Verify Identity →
            </button>
        </form>

        <div class="toggle-recovery" id="toggleRecovery">
            Lost device? Use emergency recovery code
        </div>
    </div>

    <script>
        const form = document.getElementById('totpForm');
        const alertBox = document.getElementById('alertBox');
        const btnSubmit = document.getElementById('btnSubmit');
        const codeInput = document.getElementById('code');
        const toggleRecovery = document.getElementById('toggleRecovery');
        let recoveryMode = false;

        toggleRecovery.addEventListener('click', () => {
            recoveryMode = !recoveryMode;
            if (recoveryMode) {
                codeInput.placeholder = 'xxxx-xxxx';
                codeInput.style.letterSpacing = '0.1em';
                codeInput.style.fontSize = '1rem';
                toggleRecovery.textContent = 'Switch back to 6-digit Google Authenticator code';
            } else {
                codeInput.placeholder = '000000';
                codeInput.style.letterSpacing = '0.35em';
                codeInput.style.fontSize = '1.4rem';
                toggleRecovery.textContent = 'Lost device? Use emergency recovery code';
            }
        });

        form.addEventListener('submit', async (e) => {
            e.preventDefault();
            alertBox.style.display = 'none';
            btnSubmit.disabled = true;
            btnSubmit.textContent = 'Verifying...';

            try {
                const res = await fetch('<?= $appBase ?>/api/v1/auth/2fa/verify', {
                    method: 'POST',
                    headers: {
                        'Content-Type': 'application/json',
                        'Accept': 'application/json',
                        'X-CSRF-Token': '<?= $csrfToken ?>'
                    },
                    body: JSON.stringify({
                        code: codeInput.value.trim()
                    })
                });

                const data = await res.json();

                if (!res.ok) {
                    alertBox.textContent = data.message || 'Invalid code.';
                    alertBox.style.display = 'block';
                    btnSubmit.disabled = false;
                    btnSubmit.textContent = 'Verify Identity →';
                    return;
                }

                window.location.href = data.data.redirect || '<?= $appBase ?>/admin/';
            } catch (err) {
                alertBox.textContent = 'Network error during verification.';
                alertBox.style.display = 'block';
                btnSubmit.disabled = false;
                btnSubmit.textContent = 'Verify Identity →';
            }
        });
    </script>
